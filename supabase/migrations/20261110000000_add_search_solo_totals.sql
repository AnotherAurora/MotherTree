-- Precomputed Public Search solo-kit totals.
--
-- Search used to run the whole Path Carver pipeline for every
-- (awakener, realm, enlightenment) pair inside the Cloudflare Worker, which
-- exceeds the Workers Free 10 ms CPU budget (error 1102). The values are a pure
-- function of (awakener, realm, enlightenment, tag), so they are precomputed
-- offline by `npm run sync:search-totals` and only read at request time.
--
-- Only tags flagged `tag.is_search_simulated` are stored. Display fields are
-- precomputed too because collectSoloTagDisplayFields scans the awakener's
-- manifestations per row.

CREATE TABLE IF NOT EXISTS public.search_solo_totals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  awakener_id integer NOT NULL REFERENCES public.awakener(id) ON DELETE CASCADE,
  realm_id integer NOT NULL REFERENCES public.realm(id) ON DELETE CASCADE,
  enlightenment integer NOT NULL,
  tag_id integer NOT NULL REFERENCES public.tag(id) ON DELETE CASCADE,
  value double precision NOT NULL,
  has_realm_gimmick boolean NOT NULL DEFAULT false,
  target_type_display text,
  metadata_display text,
  synced_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT search_solo_totals_key_unique
    UNIQUE (awakener_id, realm_id, enlightenment, tag_id)
);

CREATE INDEX IF NOT EXISTS search_solo_totals_lookup_idx
  ON public.search_solo_totals (tag_id, enlightenment);

COMMENT ON TABLE public.search_solo_totals IS
  'Public Search precomputed solo-kit totals; regenerated by npm run sync:search-totals.';

ALTER TABLE public.search_solo_totals ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON TABLE public.search_solo_totals TO anon;

DROP POLICY IF EXISTS anon_select_alive ON public.search_solo_totals;
CREATE POLICY anon_select_alive ON public.search_solo_totals
  FOR SELECT TO anon
  USING (true);
