ALTER TABLE ONLY public.awakener_tag_manifestation
  ADD CONSTRAINT awakener_tag_manifestation_copy_provider_group_id_fkey
  FOREIGN KEY (copy_provider_group_id) REFERENCES public.copy_provider_group (id) DEFERRABLE;

