-- Relic catalog table. Mirrors public.posse plus a variant tier column.
-- Seeds the 91 Standard Astral Reign relic families (Gold/Cursed variants).

CREATE TABLE public.relic (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name character varying NOT NULL UNIQUE,
  tier character varying NOT NULL,
  created_at timestamp without time zone,
  updated_at timestamp without time zone,
  deleted_at timestamp without time zone
);

ALTER TABLE public.relic ENABLE ROW LEVEL SECURITY;

GRANT REFERENCES, TRIGGER, TRUNCATE, MAINTAIN ON TABLE public.relic TO anon;
GRANT REFERENCES, TRIGGER, TRUNCATE, MAINTAIN ON TABLE public.relic TO authenticated;
GRANT SELECT ON TABLE public.relic TO anon;
GRANT ALL ON TABLE public.relic TO service_role;

CREATE POLICY anon_select_alive ON public.relic
  FOR SELECT TO anon
  USING (deleted_at IS NULL);

