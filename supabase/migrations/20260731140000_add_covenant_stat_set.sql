GRANT REFERENCES, TRIGGER, TRUNCATE, MAINTAIN ON TABLE public.covenant_stat_set TO authenticated;
GRANT ALL ON TABLE public.covenant_stat_set TO service_role;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

