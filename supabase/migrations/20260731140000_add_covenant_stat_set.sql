CREATE TABLE public.covenant_stat_set (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stat public.all_stats,
  stat_amount double precision,
  created_at timestamp without time zone,
  updated_at timestamp without time zone,
  deleted_at timestamp without time zone
);

ALTER TABLE public.covenant_stat_set OWNER TO postgres;

ALTER TABLE public.covenant_stat_set ENABLE ROW LEVEL SECURITY;

